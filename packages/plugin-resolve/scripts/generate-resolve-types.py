PRIMITIVES = {"str": "string", "int": "number", "float": "number", "bool": "boolean", "None": "null"}


def jsdoc(text, indent=""):
	text = (text or "").strip().replace("*/", "*\\/")
	if not text:
		return ""
	lines = [l.strip() for l in text.splitlines()]
	if len(lines) == 1:
		return f"{indent}/** {lines[0]} */\n"
	return f"{indent}/**\n" + "".join(f"{indent} * {l}".rstrip() + "\n" for l in lines) + f"{indent} */\n"


def quote_key(key):
	return key if re.fullmatch(r"[A-Za-z_$][\w$]*", key) else f'"{key}"'


class Converter:
	def __init__(self, source):
		self.source = source
		self.lines = source.splitlines()
		self.tree = ast.parse(source)
		self.objects = set()  # API object classes
		self.dicts = set()  # TypedDicts
		for node in self.tree.body:
			if isinstance(node, ast.ClassDef):
				is_dict = any(isinstance(b, ast.Name) and b.id == "TypedDict" for b in node.bases)
				(self.dicts if is_dict else self.objects).add(node.name)
			elif isinstance(node, ast.Assign) and isinstance(node.value, ast.Call):
				self.dicts.add(node.targets[0].id)

	def type(self, e, partial=False):
		"""Converts an annotation to TS. With partial, dicts are Partial<> (they're inputs)."""
		if e is None:
			return "unknown"
		if isinstance(e, ast.Constant):
			if isinstance(e.value, str):
				return self.type(ast.parse(e.value, mode="eval").body, partial)  # forward reference
			if e.value is None:
				return "null"
			return "unknown"
		if isinstance(e, ast.Name):
			if e.id == "dict":
				return "Record<string, string>"
			if e.id == "list":
				return "unknown[]"
			if partial and e.id in self.dicts:
				return f"Partial<{e.id}>"
			return PRIMITIVES.get(e.id, e.id)
		if isinstance(e, ast.BinOp) and isinstance(e.op, ast.BitOr):
			return " | ".join(dict.fromkeys(self.union(e, partial)))
		if isinstance(e, ast.Subscript):
			base = e.value.id
			args = e.slice.elts if isinstance(e.slice, ast.Tuple) else [e.slice]
			if base == "Literal":
				return " | ".join(f'"{a.value}"' if isinstance(a.value, str) else repr(a.value) for a in args)
			if base == "list":
				inner = self.type(args[0], partial)
				return f"({inner})[]" if "|" in inner else f"{inner}[]"
			if base == "dict":
				return f"Record<{self.type(args[0], partial)}, {self.type(args[1], partial)}>"
		raise ValueError(f"unsupported annotation: {ast.dump(e)}")

	def union(self, e, partial=False):
		if isinstance(e, ast.BinOp) and isinstance(e.op, ast.BitOr):
			return self.union(e.left, partial) + self.union(e.right, partial)
		return [self.type(e, partial)]

	def returns(self, e):
		members = self.union(e) if e is not None else ["null"]  # unannotated returns are None
		nullable = "null" in members
		members = [m for m in members if m != "null"]
		if not members:
			return "P<void>"
		inner = " | ".join(members)
		if any(m in self.objects for m in members):
			return f"Maybe<{inner}>"
		return f"P<{inner} | null>" if nullable else f"P<{inner}>"

	def param(self, arg, default):
		if arg.annotation is not None:
			members = [m for m in self.union(arg.annotation, partial=True) if not (default is not None and m == "null")]
			ts = " | ".join(members)
		elif isinstance(default, ast.Constant) and type(default.value).__name__ in PRIMITIVES:
			ts = PRIMITIVES[type(default.value).__name__]
		else:
			ts = "unknown"
		return f"{arg.arg}{'?' if default is not None else ''}: {ts}"

	def method(self, fn):
		args = fn.args.args[1:]  # drop self
		defaults = [None] * (len(args) - len(fn.args.defaults)) + list(fn.args.defaults)
		params = ", ".join(self.param(a, d) for a, d in zip(args, defaults))
		return jsdoc(ast.get_docstring(fn)) + f"{fn.name}({params}): {self.returns(fn.returns)};"

	@staticmethod
	def docstrings(body):
		"""Pairs each annotated field with the docstring that follows it."""
		out = []
		for i, node in enumerate(body):
			if isinstance(node, ast.AnnAssign):
				nxt = body[i + 1] if i + 1 < len(body) else None
				doc = (
					nxt.value.value
					if isinstance(nxt, ast.Expr) and isinstance(nxt.value, ast.Constant) and isinstance(nxt.value.value, str)
					else None
				)
				out.append((node, doc))
		return out

	def typed_dict(self, node):
		fields = "".join(
			jsdoc(doc, "\t") + f"\t{quote_key(f.target.id)}: {self.type(f.annotation)};\n"
			for f, doc in self.docstrings(node.body)
		)
		return jsdoc(ast.get_docstring(node)) + f"export interface {node.name} {{\n{fields}}}\n"

	def functional_typed_dict(self, name, d):
		fields = ""
		for k, v in zip(d.keys, d.values):
			comment = self.lines[k.lineno - 1].partition("#")[2]
			fields += jsdoc(comment, "\t") + f"\t{quote_key(k.value)}: {self.type(v)};\n"
		fields += "".join(f"\t{l}\n" for l in EXTRA_FIELDS.get(name, "").splitlines())
		return f"export interface {name} {{\n{fields}}}\n"

	def object_class(self, node):
		if node.name in UNTYPED:
			return f"export type {node.name} = Record<string, any>;\n"
		members = []
		for f, doc in self.docstrings(node.body):
			members.append(jsdoc(doc) + f"readonly {f.target.id}: {self.type(f.annotation)};")
		for fn in node.body:
			if isinstance(fn, ast.FunctionDef):
				members.append(OVERRIDES.get((node.name, fn.name)) or self.method(fn))
		members += EXTRA.get(node.name, [])
		if not members:
			members = [f'readonly __brand?: "{node.name}";']
		body = "".join("".join(f"\t{l}\n" if l else "\n" for l in m.splitlines()) for m in members)
		return jsdoc(ast.get_docstring(node) or ("Opaque handle, no methods." if node.name == "GalleryStill" else "")) + (
			f"export interface {node.name} {{\n{body}}}\n"
		)

	def render(self, pyi):
		updated = re.search(r"Last Updated: ([^*\n]+)", (pyi.parent / "README.md").read_text()) if (pyi.parent / "README.md").exists() else None
		parts = [
			PRELUDE.replace("{pyi}", str(pyi)).replace(
				"{updated}", f"README.md last updated {updated.group(1).strip()}" if updated else "README.md not found"
			)
		]
		values, aliases, dicts, objects = [], [], [], []
		body = self.tree.body
		for i, node in enumerate(body):
			nxt = body[i + 1] if i + 1 < len(body) else None
			doc = nxt.value.value if isinstance(nxt, ast.Expr) and isinstance(nxt.value, ast.Constant) else None
			if isinstance(node, ast.Assign) and isinstance(node.value, ast.Subscript):
				values.append(f"export type {node.targets[0].id} = {self.type(node.value)};\n")
			elif isinstance(node, ast.Assign) and isinstance(node.value, ast.Call):
				dicts.append(self.functional_typed_dict(node.targets[0].id, node.value.args[1]))
			elif isinstance(node, ast.AnnAssign):  # `X: TypeAlias = float`
				# Constant values are plain numbers that overlap across groups (0 is valid almost
				# everywhere), so each group gets a brand: only its resolve.* constants are assignable.
				name = node.target.id
				aliases.append(
					jsdoc(doc) + f'export type {name} = {self.type(node.value)} & {{ readonly __constant: "{name}" }};\n'
				)
			elif isinstance(node, ast.ClassDef):
				(objects if node.name in self.objects else dicts).append(
					self.object_class(node) if node.name in self.objects else self.typed_dict(node)
				)
		section = "\n// ---------------------------------------------------------------------------\n// {}\n\n"
		parts += [section.format("Value types"), "\n".join(values)]
		parts += [section.format("resolve.* constant types"), "\n".join(aliases)]
		parts += [section.format("Dicts"), "\n".join(dicts)]
		parts += [section.format("Objects"), "\n".join(objects)]
		return "".join(parts)


def main():
	pyi = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_PYI
	OUT.write_text(Converter(pyi.read_text()).render(pyi))
	print(f"wrote {OUT}")


if __name__ == "__main__":
	main()
